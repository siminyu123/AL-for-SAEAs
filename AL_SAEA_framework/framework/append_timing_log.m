function append_timing_log(testDir, algorithm, problemName, D, runIndex, status, elapsedSeconds, startTime, endTime, errorMessage)
% Save one timing record after each case.
% Use this to see which algorithms are slow or failed after a long time.

timingPath = fullfile(testDir, 'timing_log.csv');

newRow = table( ...
    string(algorithm), ...
    string(problemName), ...
    D, ...
    runIndex, ...
    string(status), ...
    elapsedSeconds, ...
    elapsedSeconds / 60, ...
    elapsedSeconds / 3600, ...
    startTime, ...
    endTime, ...
    string(errorMessage), ...
    'VariableNames', {'algorithm', 'problem', 'D', 'run', 'status', ...
    'seconds', 'minutes', 'hours', ...
    'startTime', 'endTime', 'errorMessage'} );

if exist(timingPath, 'file')
    oldTable = readtable(timingPath);
    timingTable = [oldTable; newRow];
else
    timingTable = newRow;
end

writetable(timingTable, timingPath);
end