function result = run_one_algorithm(alg, problemName, D, runIndex, cfg)
% Send each algorithm name to the correct wrapper.

algChar = char(alg);
algKey = upper(strrep(algChar, '-', '_'));

tsddeoAL = { ...
    'TSDDEO_AL_DIST', ...
    'TSDDEO_AL_COM', ...
    'TSDDEO_AL_DISTCOM'};

sampsAL = { ...
    'SA_MPSO_AL_A', ...
    'SA_MPSO_AL_B', ...
    'SA_MPSO_AL_C', ...
    'SA_MPSO_AL_AB', ...
    'SA_MPSO_AL_ABOR', ...
    'SA_MPSO_AL_COV', ...
    'SA_MPSO_AL_COM1', ...
    'SA_MPSO_AL_BCOV', ...
    'SA_MPSO_AL_BCOVOR', ...
    'SA_MPSO_AL_COVCOM1', ...
    'SA_MPSO_AL_COVCOM1OR', ...
    'SA_MPSO_AL_BCOVADAPT', ...
    'SA_MPSO_AL_ABADAPT', ...
    'SA_MPSO_AL_COVCOM1ADAPT'};

if ismember(algKey, tsddeoAL)
    result = wrap_TSDDEO_AL(problemName, D, runIndex, cfg, algKey);
    return;
end


if ismember(algKey, sampsAL)
    result = wrap_SA_MPSO_AL(problemName, D, runIndex, cfg, algKey);
    return;
end

switch algKey
    case 'TSDDEO'
        result = wrap_TSDDEO(problemName, D, runIndex, cfg);

    case {'SA_MPSO', 'SAMPSO', 'SA_MPSO_RECREATED'}
        result = wrap_SA_MPSO_recreated(problemName, D, runIndex, cfg);

    otherwise
        error('Unknown algorithm name: %s', algChar);
end
end